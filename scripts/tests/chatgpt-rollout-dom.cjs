// NODE_PATH=/private/tmp/ait-dom-tests/node_modules node scripts/tests/chatgpt-rollout-dom.cjs
const { JSDOM } = require('jsdom');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const dom = new JSDOM('<main><div id="turns"></div><form><h4 class="sr-only">You said:</h4><textarea></textarea></form></main>', { url: 'https://chatgpt.com/c/first', runScripts: 'outside-only' });
const w = dom.window;
w.SiteAdapter = class {};
w.eval(read('js/timeline/adapters/chatgpt-rollout.js'));
w.eval(read('js/timeline/adapters/chatgpt.js') + '\nwindow.adapter = new ChatGPTAdapter();');
const a = w.adapter;
const turns = w.document.getElementById('turns');
const add = (role, text, wrap = false) => {
    const el = w.document.createElement('section');
    const heading = `<h4 class="sr-only">${role}</h4>`;
    el.innerHTML = `${wrap ? `<div>${heading}</div>` : heading}<div class="body"></div><button>Copy</button>`;
    el.querySelector('.body').textContent = text;
    turns.append(el); return el;
};
const first = add('You said:', 'PRIVATE_QUESTION');
const reply = add('ChatGPT said:', 'PRIVATE_ANSWER', true);
const second = add('你说：', '另一个问题');
a.prepareTimelineNodes({ force: true });
assert.equal(w.document.querySelectorAll(a.getUserMessageSelector()).length, 2);
assert.equal(w.document.querySelectorAll(a.getAssistantMessageSelector()).length, 1);
assert.equal(a.extractText(first), 'PRIVATE_QUESTION');
assert.equal(a.generateTurnId(first, 0), 'chatgpt-0');
let texts = { 'message-first': 'PRIVATE_QUESTION', 'message-second': '另一个问题' };
w.document.addEventListener('ait-gpt-user-texts-pull', e => {
    w.document.dispatchEvent(new w.CustomEvent('ait-gpt-user-texts-result', { detail: JSON.stringify({ conversationId: e.detail, texts }) }));
});
a.syncCapturedChatsData();
assert.equal(a.generateTurnId(first, 0), 'chatgpt-message-first', 'late API match');
let coverage = a.getDiagnosticCoverage();
assert.equal(coverage.uniqueTextMatches, 2);
assert.equal(coverage.apiTextsWithoutUniqueDomMatch, 0);
assert(!JSON.stringify(coverage).includes('PRIVATE_QUESTION'));
assert(!JSON.stringify(coverage).includes('message-first'));
const duplicate = add('You said:', 'PRIVATE_QUESTION');
a.prepareTimelineNodes({ force: true });
assert.equal(a.generateTurnId(first, 0), 'chatgpt-0', 'duplicate DOM must not share an ID');
assert.equal(a.getDiagnosticCoverage().ambiguousTextMatches, 2);
duplicate.remove();
texts = { ...texts, 'another-branch': 'PRIVATE_QUESTION' };
a.handleCapturedChatsDataUpdated('first');
assert.equal(a.generateTurnId(first, 0), 'chatgpt-0', 'ambiguous API match must not guess');
first.remove();
a.prepareTimelineNodes({ force: true });
assert.equal(w.document.querySelectorAll(a.getUserMessageSelector()).length, 1);
texts = {};
w.history.pushState({}, '', '/c/second');
a.syncCapturedChatsData();
assert.equal(a._capturedMatchTexts.size, 0);
assert.equal(a.getDiagnosticCoverage().apiTextsSeenAcrossSnapshots, 0);
// Legacy wins, even if rollout headings are also present.
const old = w.document.createElement('article');
old.setAttribute('data-turn', 'user'); old.setAttribute('data-turn-id', 'legacy');
old.innerHTML = '<div class="whitespace-pre-wrap">OLD</div>';
turns.append(old);
a.prepareTimelineNodes({ force: true });
assert.equal(a.getUserMessageSelector(), '[data-turn="user"][data-turn-id]');
assert.equal(a.generateTurnId(old, 0), 'chatgpt-legacy');
assert.equal(a.extractText(old), 'OLD');
delete w.AITChatGPTRolloutDOM;
a.prepareTimelineNodes({ force: true });
assert.equal(a.generateTurnId(old, 0), 'chatgpt-legacy', 'rollout module removable');
old.remove();
a.prepareTimelineNodes({ force: true });
assert.equal(w.document.querySelectorAll(a.getUserMessageSelector()).length, 0);
w.close();
console.log('PASS: heading DOM, wrapped headings, new/removal, duplicate safety, late API, route reset, legacy preference, removable rollout module.');
