#!/usr/bin/env node
/**
 * Generate isolated-world modules from the existing ordered classic scripts.
 * Loading policy and module setup are documented in README.md / README.en.md.
 */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const ROOT = path.resolve(__dirname, '..');
const CONFIG_PATH = path.join(__dirname, 'content-bundles.config.json');
const readConfig = () => JSON.parse(fs.readFileSync(CONFIG_PATH, 'utf8'));

function buildContent({ check = false } = {}) {
    const config = readConfig();
    const outputs = new Map();
    const bundles = {};
    for (const [name, bundle] of Object.entries(config.bundles)) {
        // Keep dependency order within each bundle; exports form its cross-bundle API.
        const sources = bundle.scripts.map(file => `\n// Source: ${file}\n${fs.readFileSync(path.join(ROOT, file), 'utf8')}\n;`);
        const expose = bundle.exports.map(name => `${name}`).join(', ');
        const body = `// Generated by scripts/build-content.js. Edit the original source files.\n(function () {\n${sources.join('\n')}\nObject.assign(globalThis, { ${expose} });\n}).call(globalThis);\n`;
        new vm.Script(body, { filename: name });
        const script = `js/content/bundles/${name}.js`;
        outputs.set(script, body);
        bundles[name] = { script, styles: bundle.styles,
            dependencies: bundle.dependencies || (name === 'core' ? [] : ['core']),
            revision: crypto.createHash('sha256').update(body).digest('hex').slice(0, 12) };
    }

    // Read detection selectors from the adapters at build time, without shipping
    // the complete adapter registry to every ordinary web page.
    const context = vm.createContext({ window: {}, document: { querySelector: () => null, querySelectorAll: () => [] } });
    const base = 'js/timeline/adapters/base.js';
    vm.runInContext(fs.readFileSync(path.join(ROOT, base), 'utf8'), context);
    const platformSelectors = [];
    for (const file of config.bundles.core.scripts.filter(file => /^js\/timeline\/adapters\//.test(file)
        && !/(?:base|custom|registry)\.js$/.test(file))) {
        const source = fs.readFileSync(path.join(ROOT, file), 'utf8');
        const className = source.match(/^class (\w+)/m)?.[1];
        if (!className) continue;
        vm.runInContext(source, context);
        const selector = vm.runInContext(`new ${className}().getUserMessageSelector()`, context);
        const platformId = path.basename(file, '.js');
        // GPT's modern timeline tags are supplied by the extension itself;
        // mirror detection must recognize the native user-message markup.
        const selectors = platformId === 'chatgpt'
            ? [selector, '[data-message-author-role="user"]']
            : platformId === 'claude'
                ? [selector, '[data-testid="transcript-row"]:has([data-testid="user-message"])']
                : [selector];
        for (const value of new Set(selectors.filter(Boolean))) platformSelectors.push({ platformId, selector: value });
    }
    vm.runInContext(fs.readFileSync(path.join(ROOT, 'js/formula/formula-manager.js'), 'utf8'), context);
    const formulaSelector = vm.runInContext('FormulaManager.getDetectionSelectors().join(", ")', context);
    outputs.set('js/content/config.js', `// Generated by scripts/build-content.js.\nglobalThis.AITContentConfig = ${JSON.stringify({ bundles, platformSelectors,
        pageFeatureSelectors: { formula: formulaSelector }, detectorStorageKey: 'customTimelineAdapterDetecting' }, null, 2)};\n`);

    const stale = [];
    for (const [file, content] of outputs) {
        const target = path.join(ROOT, file);
        if (check) {
            if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) stale.push(file);
        } else {
            fs.mkdirSync(path.dirname(target), { recursive: true });
            if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) fs.writeFileSync(target, content);
        }
    }
    if (stale.length) throw new Error(`Content bundles need rebuilding: ${stale.join(', ')}. Run node scripts/build-content.js`);
    return { bundles, outputs: [...outputs.keys()] };
}

function watchContent() {
    const watchers = new Map();
    let timer;
    let closed = false;

    function watch(file) {
        if (watchers.has(file)) return;
        const listener = () => schedule();
        // Stat polling survives atomic saves without consuming filesystem event handles.
        fs.watchFile(file, { interval: 500 }, listener);
        watchers.set(file, listener);
    }

    function rebuild() {
        try {
            const config = readConfig();
            const inputs = new Set([CONFIG_PATH, ...config.bootstrap.map(file => path.join(ROOT, file)),
                ...Object.values(config.bundles).flatMap(bundle => bundle.scripts.map(file => path.join(ROOT, file)))]);
            for (const file of inputs) watch(file);
            for (const [file, listener] of watchers) {
                if (inputs.has(file)) continue;
                fs.unwatchFile(file, listener);
                watchers.delete(file);
            }
            buildContent();
            console.log('[content] Bundles updated. Reload the extension and refresh the target page.');
        } catch (error) {
            console.error(`[content] Build failed: ${error.message}\n[content] Still watching; save your changes to retry.`);
        }
    }

    function schedule() {
        if (closed) return;
        clearTimeout(timer);
        timer = setTimeout(rebuild, 150);
    }

    function close() {
        if (closed) return;
        closed = true;
        clearTimeout(timer);
        for (const [file, listener] of watchers) fs.unwatchFile(file, listener);
        watchers.clear();
        process.removeListener('SIGINT', close);
        process.removeListener('SIGTERM', close);
    }

    watch(CONFIG_PATH);
    process.once('SIGINT', close);
    process.once('SIGTERM', close);
    rebuild();
    console.log('[content] Watching JavaScript sources and the bundle config. Press Ctrl+C to stop.');
    return close;
}

if (require.main === module) {
    const args = process.argv.slice(2);
    if (args.includes('--watch') && args.includes('--check')) {
        console.error('Use either --watch or --check, not both.');
        process.exitCode = 1;
    } else if (args.includes('--watch')) {
        watchContent();
    } else {
        buildContent({ check: args.includes('--check') });
    }
}
module.exports = { buildContent, watchContent, get config() { return readConfig(); } };
